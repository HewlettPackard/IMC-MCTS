import hashlib
import json
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parents[2]
DEST=ROOT/'rtl_synthesis/p04_column_hold'


def replace_once(text, old, new):
    if text.count(old)!=1: raise ValueError('Unexpected source pattern: '+old)
    return text.replace(old,new,1)


def main():
    proof=json.loads((ROOT/'core/architecture/complete_controller_validation.json').read_text())
    inputs=['rtl_synthesis/p01_mapped_core/p00_rtl/imc_neural_sequencer.sv',
        'rtl_synthesis/p01_mapped_core/p00_rtl/imc_neural_core.sv',
        'rtl_synthesis/p03_iteration_core/p00_rtl/imc_iteration_core.sv']
    hashes={}
    ports='''
    output logic                    column_capture_valid,
    input  logic                    column_capture_ready,
    output logic [8:0]              column_capture_columns,
    output logic                    column_bank_clear,
    output logic                    column_bank_valid,'''
    connections='''
        .column_capture_valid(column_capture_valid),
        .column_capture_ready(column_capture_ready),
        .column_capture_columns(column_capture_columns),
        .column_bank_clear(column_bank_clear),
        .column_bank_valid(column_bank_valid),'''
    for name in inputs:
        path=ROOT/name; hashes[name]=hashlib.sha256(path.read_bytes()).hexdigest()
        if name in proof['validated_sources'] and hashes[name]!=proof['validated_sources'][name]:
            raise ValueError('Preserved RTL identity changed: '+name)
        text=path.read_text(); module=path.stem
        target=module.replace('imc_','imc_buffered_',1)
        text=replace_once(text,'module '+module+' #(','module '+target+' #(')
        text=re.sub(r'(^\s*output logic\s+array_enable,)',lambda m:m[1]+ports,text,count=1,flags=re.M)
        if module=='imc_neural_sequencer':
            text=replace_once(text,'        ST_RESULT\n','        ST_RESULT, ST_CAPTURE\n')
            text=replace_once(text,'    integer i, j;','    logic capture_ready, hold_error;\n    integer i, j;')
            text=replace_once(text,'    assign ready =', '''    assign column_capture_columns = tile_columns;
    assign column_bank_clear = !rst_n || state_q == ST_IDLE || state_q == ST_RESULT;

    imc_column_hold_control #(.COLUMNS(128), .ARRAYS(FIRST_ARRAYS + 1)) u_column_hold (
        .clk(clk),
        .rst_n(rst_n),
        .clear(column_bank_clear),
        .capture_req(state_q == ST_CAPTURE),
        .capture_array(array_id),
        .capture_columns(tile_columns[7:0]),
        .capture_ready(capture_ready),
        .analog_capture_valid(column_capture_valid),
        .analog_capture_ready(column_capture_ready),
        .sample_valid(sample_hold),
        .sample_array(array_id),
        .sample_first(column_q),
        .sample_count(column_count),
        .holding(column_bank_valid),
        .protocol_error(hold_error)
    );

    assign ready =''')
            text=replace_once(text,"if (settle_q == 2'd1) state_d = ST_MUX;","if (settle_q == 2'd1) state_d = ST_CAPTURE;")
            text=replace_once(text,'            ST_MUX: begin','            ST_CAPTURE: begin\n                if (capture_ready) state_d = ST_MUX;\n            end\n            ST_MUX: begin')
            text=replace_once(text,'ST_DRIVE, ST_SETTLE, ST_MUX, ST_SAMPLE, ST_ADC_REQ, ST_ADC_WAIT, ST_READOUT, ST_ACCUM:',
                'ST_DRIVE, ST_SETTLE, ST_CAPTURE:')
            text=replace_once(text,"        if (state_d == ST_RESULT && error_d != '0)",
                "        if (hold_error) begin\n            error_d = 4'd8;\n            state_d = ST_RESULT;\n        end\n        if (state_d == ST_RESULT && error_d != '0)")
        else:
            text=replace_once(text,'    imc_neural_sequencer #(','    imc_buffered_neural_sequencer #(')
            text=replace_once(text,'        .array_enable(array_enable),','        .array_enable(array_enable),'+connections)
        text='// Buffered variant generated by p18_buffered_hardware/generate_rtl.py.\n// Array drive ends after external column capture; analog storage is not RTL.\n'+text
        output=DEST/'p00_rtl'/(target+'.sv'); output.parent.mkdir(parents=True,exist_ok=True); output.write_text(text)
    lines=(ROOT/'rtl_synthesis/p03_iteration_core/filelist.f').read_text().splitlines()
    files=['p00_rtl/imc_column_hold_control.sv']
    for name in lines:
        if name.endswith('/imc_neural_sequencer.sv'): files.append('p00_rtl/imc_buffered_neural_sequencer.sv')
        elif name.endswith('/imc_iteration_core.sv'): files.append('p00_rtl/imc_buffered_iteration_core.sv')
        else: files.append('../p03_iteration_core/'+name)
    files.append('p00_rtl/imc_buffered_neural_core.sv')
    (DEST/'filelist.f').write_text('\n'.join(files)+'\n')
    tests=DEST/'p01_tests'; tests.mkdir(exist_ok=True)
    for package,base in [('p01_mapped_core','imc_neural_core'),('p03_iteration_core','imc_iteration_core')]:
        source=ROOT/'rtl_synthesis'/package/'p01_tests'/('tb_'+base+'.sv')
        hashes[str(source.relative_to(ROOT))]=hashlib.sha256(source.read_bytes()).hexdigest()
        text=source.read_text().replace(base,base.replace('imc_','imc_buffered_',1))
        if base=='imc_neural_core':
            text=replace_once(text,'if (!array_enable ||','if (array_enable ||')
            text=replace_once(text,'pending_codes = adc_vectors[adc_index][23:0];','pending_codes = sampled_codes;')
            declarations='    localparam int HOLD_ADC_LIMIT = ADC_GROUPS;\n    wire signed [31:0] hold_run = run_index;\n'
        else:
            text=replace_once(text,'adc_rsp_codes<=adc_vector[23:0];','adc_rsp_codes<=sampled_codes;')
            declarations="    wire signed [31:0] HOLD_ADC_LIMIT = adc_count;\n    wire signed [31:0] hold_run = int'(iterations_completed);\n"
        text=replace_once(text,'    always @(negedge clk)',declarations+'    `include "p01_tests/held_columns.svh"\n    always @(negedge clk)')
        (tests/('tb_'+base.replace('imc_','imc_buffered_',1)+'.sv')).write_text(text)
    source=ROOT/'p03_experiments/p12_complete_core/fixtures_complete.py'
    hashes[str(source.relative_to(ROOT))]=hashlib.sha256(source.read_bytes()).hexdigest()
    text=replace_once(source.read_text(),'    memory=model.memory','    from core.architecture.analog_readout import BUFFERED, configure_readout\n    configure_readout(model, BUFFERED)\n    memory=model.memory')
    (Path(__file__).parent/'fixtures_buffered.py').write_text('# Generated buffered fixture variant; preserves the original fixture builder.\n'+text)
    (DEST/'generation.json').write_text(json.dumps({'source_sha256':hashes,'generator':str(Path(__file__).relative_to(ROOT)),
        'boundary':'Preserved original modules; all buffered differences are generated by explicit checked transformations'},indent=2)+'\n')
    print('Generated three buffered RTL variants and filelist')


if __name__=='__main__': main()
